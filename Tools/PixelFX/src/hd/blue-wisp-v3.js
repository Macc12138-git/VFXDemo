function path(g,points,tension=.16){
  const n=points.length;g.beginPath();g.moveTo(...points[0]);
  for(let i=0;i<n;i++){
    const p=points[i],q=points[(i+1)%n],a=points[(i+n-1)%n],b=points[(i+2)%n];
    const k=tension;
    g.bezierCurveTo(p[0]+(q[0]-a[0])*k,p[1]+(q[1]-a[1])*k,q[0]-(b[0]-p[0])*k,q[1]-(b[1]-p[1])*k,q[0],q[1]);
  }g.closePath();
}
function shape(g,pts,c,t=.16){path(g,pts,t);g.fillStyle=c;g.fill();}
function glow(g,o){
  const q=g.createRadialGradient(10.7,12.3,1,10.7,12.3,19);
  const rgba=(a)=>`rgba(16,175,255,${a*o.glow})`;
  q.addColorStop(0,rgba(.26));q.addColorStop(.55,rgba(.12));q.addColorStop(.8,rgba(.025));q.addColorStop(1,rgba(0));
  g.fillStyle=q;g.beginPath();g.arc(10.7,12.3,19,0,Math.PI*2);g.fill();
}
export function draw(g,t,input={}){
  const o=options(input),pose=Number.isInteger(input.pose)?input.pose:poseAt(t),p=poses[pose],L=o.layers;
  g.save();g.scale(o.radius/11.5,o.radius/11.5);g.translate(-11.5,-12.5);
  if(input.buffer!=='light'){
    if(L.body){
      shape(g,p.outer,o.edge);
      g.save();path(g,p.outer);g.clip();
      // Per-pose painted rim weights: thick shadow islands and near-open cyan edges,
      // not one uniformly inset outline. These landmarks never oscillate over time.
      const cyan=p.outer.map(([x,y],i)=>{const s=p.rim[i]??.95;return[11.5+(x-11.5)*s,12.5+(y-12.5)*s];});
      shape(g,cyan,o.cyan);g.restore();
    }
    if(L.blue)for(const s of p.blue)shape(g,s,o.blue,.13);
    if(L.pale)for(const s of p.pale)shape(g,s,o.pale,.13);
    if(L.core){
      // The measured white area changes markedly across the four reference poses.
      // Keep that change instead of replacing it with a fixed circular nucleus.
      const coreScale=[1.14,1.18,1.19,1.16][pose];
      g.save();g.translate(7.5,12.5);g.scale(coreScale,coreScale);g.translate(-7.5,-12.5);
      shape(g,p.core,o.core,.12);if(p.core2)shape(g,p.core2,o.core,.12);g.restore();
    }
    if(L.chips)for(const s of p.chips){
      shape(g,s,o.edge,.11);g.save();
      const cx=s.reduce((a,p)=>a+p[0],0)/s.length,cy=s.reduce((a,p)=>a+p[1],0)/s.length;
      g.translate(cx,cy);g.scale(.84,.78);g.translate(-cx,-cy);shape(g,s,o.cyan,.08);g.restore();
    }
  }
  if(input.buffer!=='color'&&L.glow&&o.glow>0){g.globalCompositeOperation='lighter';glow(g,o);}
  g.restore();return {pose,o};
}
export function background(g,W,H,bg='gray'){
  if(bg==='transparent')return;
  g.fillStyle=({gray:'#454545',dark:'#0b1523',light:'#e0e7eb',checker:'#263440',warm:'#695446'})[bg]??bg;g.fillRect(0,0,W,H);
  if(bg==='checker'){g.fillStyle='#1d2833';for(let y=0;y<H;y+=24)for(let x=0;x<W;x+=24)if((x/24+y/24)%2===0)g.fillRect(x,y,24,24);}
}
export function render(canvas,t,input={},view={}){
  const g=canvas.getContext('2d'),W=canvas.width,H=canvas.height;g.resetTransform();g.clearRect(0,0,W,H);background(g,W,H,view.background??'gray');
  const s=view.scale??Math.min(W/960,H/600);g.save();g.translate(W*(view.anchorX??.405),H*.5);g.scale(s,s);draw(g,t,input);g.restore();
}
