#!/usr/bin/env node
// Authoring preview only. No Unity export, atlas generation, or Assets writes.
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { draw, meta } from '../src/hd/brazier-handpainted.js';
const flags={};
for(let i=2;i<process.argv.length;i+=2)flags[process.argv[i].replace(/^--/,'')]=process.argv[i+1];
const {createCanvas,loadImage}=await import(flags['canvas-module']?pathToFileURL(resolve(flags['canvas-module'])).href:'@napi-rs/canvas');
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const out=resolve(flags.out??join(root,'output/hd/brazier-handpainted'));
const frames=flags.frames==='true',width=+(flags.width??meta.size[0]),height=Math.round(width*1.25);
mkdirSync(out,{recursive:true});if(frames)mkdirSync(join(out,'frames'),{recursive:true});
const canvas=createCanvas(width,height),ctx=canvas.getContext('2d');
const tileW=256,tileH=344,contact=createCanvas(tileW*4,tileH*2),cg=contact.getContext('2d');
const times=[0,0.5,1,1.5,2,2.5,3,3.5],opts={...meta.options};
for(let i=0;i<times.length;i++){
  draw(ctx,times[i],opts);const png=canvas.toBuffer('image/png'),snap=await loadImage(png);
  const x=i%4*tileW,y=Math.floor(i/4)*tileH;
  cg.fillStyle=i<4?'#151820':'#d0cbc5';cg.fillRect(x,y,tileW,tileH);
  cg.drawImage(snap,x,y+24,tileW,320);cg.font='12px sans-serif';cg.fillStyle=i<4?'#b4a59a':'#554c49';
  cg.fillText(`${times[i].toFixed(2)} s  /  ${i<4?'DARK':'LIGHT'}`,x+12,y+18);
  if(i===2){
    writeFileSync(join(out,'preview.png'),png);
    const poster=createCanvas(width,height),pg=poster.getContext('2d');
    pg.fillStyle='#151820';pg.fillRect(0,0,width,height);pg.drawImage(snap,0,0);
    writeFileSync(join(out,'poster.png'),poster.toBuffer('image/png'));
  }
}
writeFileSync(join(out,'contact.png'),contact.toBuffer('image/png'));
for(const [name,options] of [['flame-only',{prop:false}],['color',{layer:'color'}],['glow',{layer:'glow'}]]){
  draw(ctx,1,options);writeFileSync(join(out,`${name}.png`),canvas.toBuffer('image/png'));
}
if(frames)for(let i=0;i<meta.duration*meta.fps;i++){
  draw(ctx,i/meta.fps);writeFileSync(join(out,'frames',`brazier-${String(i).padStart(3,'0')}.png`),canvas.toBuffer('image/png'));
}
writeFileSync(join(out,'authoring.json'),JSON.stringify({...meta,outputSize:[width,height],source:'src/hd/brazier-handpainted.js',options:opts,
  sourceSha256:createHash('sha256').update(readFileSync(join(root,'src/hd/brazier-handpainted.js'))).digest('hex'),
  authorRequest:'先绘制该特效；注意使用 pixelfx-skill。',authorizedStage:'authoring-and-preview-only',
  frameCount:frames?meta.duration*meta.fps:0,status:'awaiting-author-review',unityImported:false,
  previewModel:'Canvas CPU analogue of color UV distortion, noise dissolve and rough edge; not the Unity shader.',
  differences:['Directional threshold bias and root-anchored distortion are authoring additions.',
    'Tone bands and primary tongue motion are newly drawn Canvas shapes, not generated by the Unity shader.',
    'No Unity compile, particle playback, visual parity or device-performance validation has been performed.'],
},null,2));
console.log(`${meta.name} · ${width}×${height} · seed=${opts.seed} · ${frames?'120 frames':'contact + stills'}\n${out}`);
